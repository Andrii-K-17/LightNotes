namespace LightNotes.Domain.Enums;

public enum Role
{
    Owner = 0,  // Власник нотатки: повний доступ, може запрошувати/видаляти учасників, змінювати ролі
    Editor = 1, // Редактор: може змінювати вміст нотатки, але не управляти учасниками
    Viewer = 2  // Переглядач: може тільки читати вміст нотатки
}
